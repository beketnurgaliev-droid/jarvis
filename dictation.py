# -*- coding: utf-8 -*-
"""Диктовка: «Джарвис, напиши привет как дела» → «Привет, как дела?» в
активном окне (чат, документ, строка поиска).

Распознавание отдаёт текст без знаков и заглавных — их расставляет быстрый
ИИ (по ключу, около секунды). ИИ нет или не успел — печатаем как услышали,
с заглавной буквы. Печатаем буквами через SendInput: буфер обмена не трогаем.
"""

import logging
import re

import brain
import sendkeys
import windows

log = logging.getLogger("jarvis.dictation")

_DICTATE = re.compile(r"^(?:напиши|напечатай|набери)(?:\s+(?:текст|мне|пожалуйста))*\s+(.+)$")

PROMPT = (
    "Это текст, надиктованный голосом; распознавание выдало его без знаков "
    "препинания и заглавных букв. Расставь знаки препинания и заглавные буквы, "
    "исправь явные ошибки распознавания. Слова «точка», «запятая», «вопросительный "
    "знак», «восклицательный знак», «двоеточие», «тире», «кавычки», «с новой строки» "
    "замени на сами знаки («с новой строки» — перевод строки). Больше ничего не "
    "меняй и не добавляй, на текст не отвечай. Ответ — только готовый текст.\n\nТекст: "
)


# сказанные словами знаки — заменяем сами, не дожидаясь ИИ: так текст
# правильный, даже если ИИ не ответил. «Точка» — только в конце или перед
# новой строкой: «точка зрения», «точка доступа» — это слова
_SPOKEN_MARKS = [
    (r"\s*\b(?:с\s+новой\s+строки|новая\s+строка|новый\s+абзац|абзац)\b\s*", "\n"),
    (r"\s*\bвопросительный\s+знак\b", "?"),
    (r"\s*\bвосклицательный\s+знак\b", "!"),
    (r"\s*\bзапятая\b", ","),
    (r"\s*\bдвоеточие\b", ":"),
    (r"\s*\bточка\s+с\s+запятой\b", ";"),
    (r"\s*\bмноготочие\b", "…"),
    (r"\s+\bтире\b", " —"),
    (r"\s*\bточка\s*$", "."),
    (r"\s*\bточка(?=\n)", "."),
]


def spoken_marks(text):
    """«привет запятая как дела вопросительный знак» → «Привет, как дела?»;
    заглавная — в начале и после .!? и новой строки."""
    for pattern, mark in _SPOKEN_MARKS:
        text = re.sub(pattern, mark, text)
    text = re.sub(r"([,:;])(?=\S)", r"\1 ", text)          # «дела,что» → «дела, что»
    text = re.sub(r"([.!?…])(?=[^\s\n.!?…])", r"\1 ", text)
    return re.sub(r"(^|[.!?…]\s+|\n)([a-zа-яё])", lambda m: m.group(1) + m.group(2).upper(), text.strip())


def match(t):
    """Что надиктовали, или None — это не диктовка."""
    m = _DICTATE.match(t)
    return m.group(1).strip() if m else None


def _words(s):
    return re.findall(r"[a-zа-я0-9]+", s.lower().replace("ё", "е"))


def _sane(raw, fixed):
    """ИИ расставил знаки, а не ответил на текст и не дописал своё."""
    if len(fixed) > len(raw) * 1.6 + 20:
        return False
    said = _words(raw)
    got = set(_words(fixed))
    # «точка», «запятая» превратились в знаки — их в ответе и не должно быть
    marks = {"точка", "запятая", "вопросительный", "восклицательный", "знак", "двоеточие",
             "тире", "кавычки", "новой", "строки", "с"}
    need = [w for w in said if w not in marks]
    return not need or sum(w in got for w in need) / len(need) >= 0.7


def prepare(raw, cfg):
    """Текст к печати: сказанные знаки — сразу, остальные расставляет ИИ.
    ИИ не ответил — печатаем со сказанными знаками и заглавными."""
    local = spoken_marks(raw)
    if brain.available(cfg):
        # бесплатный Gemini отвечает то за 0,7 с, то за 7 (замер 17.11.2026)
        fixed = brain.task(PROMPT + local, cfg, fast=True, max_tokens=600, timeout=7)
        fixed = fixed.strip().strip("\"«»").strip()
        if fixed and _sane(raw, fixed):
            return fixed
        if fixed:
            log.info("ИИ переписал диктовку слишком сильно — печатаю как услышал")
    return local


def run(raw, cfg):
    """Напечатать в активное окно. Вернуть, что сказать (обычно ничего)."""
    if windows.foreground() is None:
        return "Некуда печатать, сэр: нет активного окна"
    text = prepare(raw, cfg)
    # следующая надиктованная фраза не слипнется с этой
    if text[-1:] in ".!?…:;,":
        text += " "
    sent, total = sendkeys.type_text(text)
    log.info("Диктовка: напечатал %d знаков", len(text))
    if sent < total:
        return "Это окно не принимает ввод, сэр. Возможно, оно запущено от администратора"
    return None
